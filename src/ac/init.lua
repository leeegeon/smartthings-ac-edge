-- Capability Handlers

local function handle_switch_on(driver, device, command)
  log.info("[AC UI] handle_switch_on")
  local state = get_device_state(device)
  local events = state:set_power("on")
  emit_ac_events(device, events)
  save_device_state(device, state)

  -- 1) Power-on frame (N4 = 0). A change frame (N4 = 8) would only beep without powering on.
  local cur = state:get_state()
  local hex_code = protocol.build_hex_code(cur.coolingSetpoint, cur.acFanSpeed, protocol.FRAME_POWER_ON)
  log.info("[AC IR] Power ON -> transmitting power-on frame 0x" .. hex_code)
  transmit_command(driver, device, hex_code)

  -- 2) Optional follow-up frames that cannot be encoded in the power-on frame
  if not device.thread then return end
  local delay = 0
  if cur.powerCoolingMode == "on" then
    delay = delay + 1
    device.thread:call_with_delay(delay, function()
      log.info("[AC IR] Power ON with Power Cooling active -> transmitting POWER_COOLING (0x8810089)")
      transmit_command(driver, device, protocol.POWER_COOLING)
    end)
  end
  if cur.fanOscillationMode == "indirect" then
    delay = delay + 1
    device.thread:call_with_delay(delay, function()
      log.info("[AC IR] Power ON with indirect mode active -> transmitting VANE_INDIRECT (0x881309D)")
      transmit_command(driver, device, protocol.VANE_INDIRECT)
    end)
  end
end

local function handle_switch_off(driver, device, command)
  log.info("[AC UI] handle_switch_off")
  local state = get_device_state(device)
  local events = state:set_power("off")
  emit_ac_events(device, events)
  save_device_state(device, state)
  transmit_command(driver, device, protocol.POWER_OFF)
end

local function handle_set_cooling_setpoint(driver, device, command)
  local target_temp = (type(command.args) == "table" and (command.args.setpoint or command.args[1])) or command.args
  log.info(string.format("[AC UI] handle_set_cooling_setpoint: %s", tostring(target_temp)))
  local state = get_device_state(device)
  local events = state:set_cooling_setpoint(target_temp)
  emit_ac_events(device, events)
  save_device_state(device, state)
  transmit_state(driver, device, state)
end

local function handle_set_fan_oscillation_mode(driver, device, command)
  local mode = (type(command.args) == "table" and (command.args.fanOscillationMode or command.args[1])) or command.args
  log.info(string.format("[AC UI] handle_set_fan_oscillation_mode: %s", tostring(mode)))
  local state = get_device_state(device)
  local events = state:set_oscillation_mode(mode)
  emit_ac_events(device, events)
  save_device_state(device, state)

  local cur = state:get_state()
  if cur.power ~= "off" then
    if mode == "indirect" then
      log.info("[AC IR] Setting fan oscillation to indirect -> transmitting VANE_INDIRECT (0x881309D)")
      transmit_command(driver, device, protocol.VANE_INDIRECT)
    else
      log.info("[AC IR] Setting fan oscillation to direct -> transmitting VANE_DIRECT (0x8813048)")
      transmit_command(driver, device, protocol.VANE_DIRECT)
    end
  end
end

local function handle_set_power_cooling_mode(driver, device, command)
  local mode = (type(command.args) == "table" and (command.args.powerCoolingMode or command.args[1])) or command.args
  log.info(string.format("[AC UI] handle_set_power_cooling_mode: %s", tostring(mode)))
  local state = get_device_state(device)
  local events = state:set_power_cooling_mode(mode)
  emit_ac_events(device, events)
  save_device_state(device, state)
  transmit_state(driver, device, state)
end

local function handle_set_ac_fan_speed(driver, device, command)
  local speed = (type(command.args) == "table" and (command.args.acFanSpeed or command.args[1])) or command.args
  log.info(string.format("[AC UI] handle_set_ac_fan_speed: %s", tostring(speed)))
  local state = get_device_state(device)
  local events = state:set_fan_speed(speed)
  emit_ac_events(device, events)
  save_device_state(device, state)
  transmit_state(driver, device, state)
end

-- Fallback for standard airConditionerFanMode if used
local function handle_set_fan_mode(driver, device, command)
  local mode = (type(command.args) == "table" and (command.args.fanMode or command.args[1])) or command.args
  log.info(string.format("[AC UI] handle_set_fan_mode (fallback): %s", tostring(mode)))
  local map = {
    ["low"] = "low",
    ["medium"] = "medium",
    ["high"] = "high",
    ["quiet"] = "whisper",
    ["turbo"] = "high",
    ["auto"] = "low",
  }
  local target_speed = map[mode] or "low"
  local state = get_device_state(device)
  local events = state:set_fan_speed(target_speed)
  emit_ac_events(device, events)
  device:emit_event(capabilities.airConditionerFanMode.fanMode(mode))
  save_device_state(device, state)
  transmit_state(driver, device, state)
end

---------------------------------------------------------------------------
-- Lifecycle Handlers

local function device_init(driver, device)
  log.info("[AC UI] device_init for LG Air Conditioner: " .. device.device_network_id)
  local state = get_device_state(device)
  local cur = state:get_state()

  -- Emit initial device states for UI display
  device:emit_event(capabilities.switch.switch({ value = cur.power }, { state_change = true }))

  -- Emit coolingSetpoint AND coolingSetpointRange (both are required for SmartThings temperature slider)
  device:emit_event(capabilities.thermostatCoolingSetpoint.coolingSetpointRange({
    value = { minimum = state_manager.MIN_TEMP, maximum = state_manager.MAX_TEMP, step = 1 },
    unit = "C"
  }, { state_change = true }))
  device:emit_event(capabilities.thermostatCoolingSetpoint.coolingSetpoint({
    value = cur.coolingSetpoint,
    unit = "C"
  }, { state_change = true }))

  -- Initialize fan oscillation mode with indirect and direct options (supported and available)
  local osc_modes = { "indirect", "direct" }
  device:emit_event(capabilities.fanOscillationMode.supportedFanOscillationModes(osc_modes, { state_change = true }))
  device:emit_event(capabilities.fanOscillationMode.availableFanOscillationModes(osc_modes, { state_change = true }))
  device:emit_event(capabilities.fanOscillationMode.fanOscillationMode({ value = cur.fanOscillationMode }, { state_change = true }))

  -- Initialize custom capabilities
  if capability_acFanSpeed then
    device:emit_event(capability_acFanSpeed.acFanSpeed({ value = cur.acFanSpeed }, { state_change = true }))
  end
  if capability_powerCoolingMode then
    local pcm_val = (cur.powerCoolingMode == "power" or cur.powerCoolingMode == "on") and "on" or "off"
    device:emit_event(capability_powerCoolingMode.powerCoolingMode({ value = pcm_val }, { state_change = true }))
  end

  save_device_state(device, state)
end

local function device_added(driver, device)
  log.info("[AC UI] device_added for LG Air Conditioner: " .. device.device_network_id)
  device_init(driver, device)
end

---------------------------------------------------------------------------
-- Sub-driver definition

local ac_sub_driver = {
  NAME = "LGAirConditioner",
  can_handle = function(opts, driver, device, ...)
    if device.device_network_id and device.device_network_id:find("^BroadlinkRM_AC") then
      return true
    end
    if device.model == "MNQ0720C2S" or (device.preferences and device.preferences.minTemp ~= nil) then
      return true
    end
    return false
  end,
  lifecycle_handlers = {
    init = device_init,
    added = device_added,
  },
  capability_handlers = {
    [capabilities.switch.ID] = {
      [capabilities.switch.commands.on.NAME] = handle_switch_on,
      [capabilities.switch.commands.off.NAME] = handle_switch_off,
    },
    [capabilities.thermostatCoolingSetpoint.ID] = {
      [capabilities.thermostatCoolingSetpoint.commands.setCoolingSetpoint.NAME] = handle_set_cooling_setpoint,
    },
    [capabilities.fanOscillationMode.ID] = {
      [capabilities.fanOscillationMode.commands.setFanOscillationMode.NAME] = handle_set_fan_oscillation_mode,
    },
    [capabilities.airConditionerFanMode.ID] = {
      [capabilities.airConditionerFanMode.commands.setFanMode.NAME] = handle_set_fan_mode,
    },
  },
}

-- Register custom capability handlers if capabilities are loaded
if capability_powerCoolingMode then
  ac_sub_driver.capability_handlers[capability_powerCoolingMode.ID] = {
    [capability_powerCoolingMode.commands.setPowerCoolingMode.NAME] = handle_set_power_cooling_mode,
  }
end

if capability_acFanSpeed then
  ac_sub_driver.capability_handlers[capability_acFanSpeed.ID] = {
    [capability_acFanSpeed.commands.setAcFanSpeed.NAME] = handle_set_ac_fan_speed,
  }
end

return ac_sub_driver
