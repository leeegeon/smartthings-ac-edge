-- src/ac/init.lua
-- SmartThings Edge sub-driver for LG Air Conditioner MNQ0720C2S
-- Handles UI capabilities and transmits LG 28-bit IR commands via Broadlink.

local log = require("log")
local capabilities = require("st.capabilities")
local state_manager = require("ac.state")
local protocol = require("ac.protocol")
local broadlink = require("broadlink")

-- Custom capabilities
local capability_powerCoolingMode = capabilities["optiontomorrow57882.powerCoolingMode"]
  or capabilities["forgottenpeace60271.powerCoolingMode"]
local capability_acFanSpeed = capabilities["optiontomorrow57882.acFanSpeed"]
  or capabilities["forgottenpeace60271.acFanSpeed"]

-- Helper to emit events generated by the state manager
local function emit_ac_events(device, events)
  if not events then return end
  for _, evt in ipairs(events) do
    if evt.capability == "switch" then
      log.info(string.format("[AC UI] Emitting switch: %s", evt.value))
      device:emit_event(capabilities.switch.switch(evt.value))
    elseif evt.capability == "coolingSetpoint" then
      log.info(string.format("[AC UI] Emitting coolingSetpoint: %d %s", evt.value, evt.unit or "C"))
      device:emit_event(capabilities.thermostatCoolingSetpoint.coolingSetpoint({ value = evt.value, unit = evt.unit or "C" }))
    elseif evt.capability == "fanOscillationMode" then
      log.info(string.format("[AC UI] Emitting fanOscillationMode: %s", evt.value))
      device:emit_event(capabilities.fanOscillationMode.fanOscillationMode(evt.value))
    elseif evt.capability == "powerCoolingMode" and capability_powerCoolingMode then
      local pcm_val = (evt.value == "power" or evt.value == "on") and "on" or "off"
      log.info(string.format("[AC UI] Emitting powerCoolingMode: %s", pcm_val))
      device:emit_event(capability_powerCoolingMode.powerCoolingMode({ value = pcm_val }, { state_change = true }))
    elseif evt.capability == "acFanSpeed" and capability_acFanSpeed then
      log.info(string.format("[AC UI] Emitting acFanSpeed: %s", evt.value))
      device:emit_event(capability_acFanSpeed.acFanSpeed({ value = evt.value }, { state_change = true }))
    end
  end
end

-- Get or initialize state manager instance for device
local function get_device_state(device)
  local state = device:get_field("ac_state_instance")
  if not state then
    local persisted = device:get_field("ac_state_data") or {}
    state = state_manager.new(persisted)
    device:set_field("ac_state_instance", state)
  end
  return state
end

-- Persist current state in device store
local function save_device_state(device, state)
  device:set_field("ac_state_data", state:get_state(), { persist = true })
end

-- Check if a device is the Broadlink hardware bridge
local function is_broadlink_device(dev)
  if not dev then return false end
  local dni = dev.device_network_id or ""
  if dni:match("^%x%x:%x%x:%x%x:%x%x:%x%x:%x%x$") or dni:find("34:8e:89") then
    return true
  end
  if dev.model and (dev.model:find("^RM") or dev.model == "RM mini 3") then
    return true
  end
  if dev.vendor_provided_label and dev.vendor_provided_label:find("^Broadlink IR Remote ") then
    return true
  end
  return false
end

-- Find the Broadlink RM hardware device and ensure IP & auth are ready
local function get_broadlink_device(driver, device)
  local broadlink_dev = device:get_parent_device()
  if not broadlink_dev or not is_broadlink_device(broadlink_dev) then
    for _, dev in pairs(driver:get_devices()) do
      if is_broadlink_device(dev) then
        broadlink_dev = dev
        break
      end
    end
  end

  if not broadlink_dev then
    log.warn("[AC IR] No Broadlink hardware device found among registered devices")
    return nil
  end

  -- Ensure IP is configured
  local ip = broadlink_dev:get_field("ip")
  if not ip or ip == "" then
    ip = (driver._macaddr_to_ip and driver._macaddr_to_ip[broadlink_dev.device_network_id]) or "192.168.0.220"
    log.info("[AC IR] Populating Broadlink device IP: " .. ip)
    broadlink_dev:set_field("ip", ip, { persist = true })
  end

  if not broadlink_dev:get_field("broadlink_device_type") then
    local dt = (driver._macaddr_to_device_type and driver._macaddr_to_device_type[broadlink_dev.device_network_id]) or 0x5f36
    broadlink_dev:set_field("broadlink_device_type", dt, { persist = true })
  end

  -- Ensure authenticated
  if not broadlink_dev:get_field("broadlink_encryption_key") then
    log.info("[AC IR] Authenticating Broadlink device before transmission")
    broadlink.auth(broadlink_dev)
  end

  return broadlink_dev
end

-- Transmit an IR command via Broadlink
local function transmit_command(driver, device, hex_code)
  local broadlink_dev = get_broadlink_device(driver, device)
  if not broadlink_dev then
    log.warn("[AC IR] Broadlink device not found; skipping IR transmission")
    return false, "broadlink device not found"
  end

  local b64_code, err = protocol.encode_to_broadlink_code(hex_code)
  if not b64_code then
    log.error("[AC IR] Failed to encode hex code to Broadlink format: " .. tostring(err))
    return false, err
  end

  log.info(string.format("[AC IR] Transmitting IR (hex=0x%s) to Broadlink: %s", hex_code, broadlink_dev.device_network_id))
  broadlink.send_data(b64_code, broadlink_dev)
  return true
end

-- Transmit current operating state while the AC is running (single "change" frame)
local function transmit_state(driver, device, state)
  local cur = state:get_state()
  if cur.power == "off" then
    log.info("[AC IR] Power is OFF; skipping operational state transmission")
    return
  end

  if cur.powerCoolingMode == "on" then
    log.info("[AC IR] Power Cooling is ON; transmitting jet cool command")
    transmit_command(driver, device, protocol.POWER_COOLING)
    return
  end

  local hex_code = protocol.build_hex_code(cur.coolingSetpoint, cur.acFanSpeed, protocol.FRAME_CHANGE)
  transmit_command(driver, device, hex_code)
end

